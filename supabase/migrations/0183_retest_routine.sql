-- 0183: 「단원평가에 막힘」 을 카드에서 **할일**로 옮긴다
--
-- 원장님 (2026-08-29) — 대시보드 카드를 없애고 「재시험지 만들기」 가
-- 할일에 저절로 뜨게. 처리하면 사라지고, 다시 안 생기게.
--
-- ── 왜 카드로는 안 됐나 ────────────────────────────────────
--
-- 카드는 「누구가 어느 단원 몇 번째」 를 말해줄 뿐 **체크할 수가 없었다.**
-- 원장님이 재시험지를 만들어 드린 뒤에도, 그 아이가 다음 시험을 볼 때까지
-- 카드는 그대로 떠 있었다. 끌 수 없는 알림은 며칠 안에 배경이 되고,
-- 그때부터는 진짜 막힌 아이도 안 보인다 (0112 에서 배운 그대로).
--
-- ── 표를 새로 만들지 않는다 ────────────────────────────────
--
-- 0082 의 todo_routines 가 이미 「규칙을 적어두면 때가 왔을 때 할일이
-- 생긴다」 를 한다. 0083 이 거기에 **사건** 갈래를 둘 더했다 (신규 학생 ·
-- 교재 끝나감). 이번 것은 세 번째 사건이므로 **줄 하나**면 된다 —
-- 칸도 표도 안 늘어난다. 갈래 이름만 늘어난다:
--
--   retest  같은 단원을 세 번째 다시 봐도 못 넘으면, 그 학생·그 단원마다 한 번
--
-- 열쇠(tasks.auto_key)
--   routine:<id>:<날짜>                       — 날짜로 되풀이 (0082)
--   routine:<id>:s:<학생id>                   — 신규 학생 (0083)
--   routine:<id>:b:<학생id>:<교재id>:<회독>   — 교재 끝나감 (0083)
--   routine:<id>:r:<학생id>:<단원>:<몇번째>   — 단원평가 막힘 (여기)
--
-- **「몇 번째」 가 열쇠에 들어간다.** 교재 끝나감에 회독이 들어간 것과 같은
-- 까닭이다. 세 번째에 만들어 드린 재시험지로 네 번째를 봤는데 또 못
-- 넘었으면 재시험지를 **또** 만들어야 하니, 그건 되살아난 것이 아니라
-- 새로 생긴 일이다. 반대로 **같은 번째는 몇 번을 열어도 한 줄**이다 —
-- auto_key 는 통째로 유일하고(0028·0061) syncRoutines 는 이미 있는 열쇠에
-- 손대지 않으므로, 체크해 넘기신 것이 화면을 다시 연다고 되살아나지 않는다.
-- 통과하면 그 단원은 아예 막힌 것이 아니게 되어(lib/unitStreak 의 passed)
-- 다음 번째도 안 생긴다.
--
-- ── 세 번째부터인 까닭 ─────────────────────────────────────
--
-- 두 번은 흔하다 (한 번 미끄러지고 다음에 통과). 판정은 코드 한 곳에 있다 —
-- lib/unitStreak.js 의 RETEST_WARN_AT = 3. 여기서 다시 적지 않는다.
--
-- ── 규칙 줄은 여기서 깔고, 그다음은 원장님 것 ──────────────
--
-- 0179 와 같은 처지다 — todo_routines 는 **DB 행**이라 원장님이 화면
-- (할일 → 되풀이되는 할일)에서 제목·분류·메모를 고치시거나 아예 끄실 수
-- 있다. 여기서 하는 일은 첫 줄을 깔아드리는 것까지다. 이 줄이 없으면
-- 카드만 사라지고 아무도 말을 안 하게 되므로 반드시 깐다.
--
-- 두 번 돌려도 한 줄이다 (아래 not exists).

insert into public.todo_routines
  (title, repeat_kind, lead_days, priority, note, active, sort)
select
  '재시험지 만들기',
  'retest',
  0,
  1,
  '세 번째 다시 봐도 못 넘은 단원입니다. 같은 문제로 또 보면 또 막히니 설명을 다시 하고 문제를 바꿔서 내주세요.',
  true,
  20
where not exists (
  select 1 from public.todo_routines where repeat_kind = 'retest'
);

-- 밖에서 「이 SQL 을 돌렸나」 를 물어볼 자국. 표·칸이 안 바뀌는 데이터
-- 전용 마이그레이션이라(0179 와 같은 처지) 표식 함수로만 확인할 수 있다.
-- **줄이 실제로 있는지** 를 본다 — 함수만 생기고 줄이 없으면 카드도 없고
-- 할일도 없는 상태가 조용히 이어진다.
create or replace function public.retest_routine_on()
returns boolean language sql stable as $$
  select exists (select 1 from public.todo_routines where repeat_kind = 'retest')
$$;
grant execute on function public.retest_routine_on() to authenticated;

