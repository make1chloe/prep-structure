-- 0179: 고정 할일 — 되풀이되는 것들의 첫 줄을 깔아둔다
--
-- 원장님 (2026-08-28) — 「애초에 고정 할일이 몇 개 있으면 좋을 것 같음.
-- 매달·매주·매년·매학기·매시험 반복되는 일이라서 확인해야 하는 것들」
--   · 매달: 회차 확정 · 수강료 안내
--   · 상시: 시험범위 등록
--
-- ── 세 가지 중 **하나만** 여기 넣는다 ────────────────────────
--
-- 되풀이 장치(0082 todo_routines)는 **DB 행**이다. 코드 상수가 아니라
-- 원장님이 화면(할일 → 되풀이되는 할일)에서 직접 더하고 고치고 끄실 수
-- 있다. 그래서 여기서 하는 일은 「첫 줄을 깔아드리는 것」 까지다.
--
-- 그런데 셋 중 둘은 **이미 남은 일 목록이 말하고 있다** (lib/menuBadges):
--
--   · 회차 확정   → schedule 키. 매달 25일부터 「다음 달 회차 미확정 N명」.
--                   month_confirms 를 실제로 읽어서 **아직 안 찍은 사람 수**를
--                   센다. 다 찍으면 저절로 꺼진다.
--   · 시험범위 등록 → prep 키. 앞으로 60일 안의 시험 중 범위가 비어 있는 것.
--                   시험이 잡히면 뜨고, 범위를 넣으면 꺼진다. 「매시험」 이
--                   딱 이것이다.
--
-- 이 둘을 고정 할일로 또 만들면 같은 일이 두 줄로 뜬다. 하나는 「했음」 을
-- 눌러야 꺼지고 하나는 저절로 꺼지므로, 언젠가 반드시 둘이 다른 말을 한다
-- (원칙 1 — 같은 값 두 번). 그래서 안 만든다.
--
--   · 수강료 안내 → **아무 데서도 안 센다.** 수강료 미납은 대시보드·메뉴에서
--                   일부러 안 알린다 (원장님 2026-08-05 — 「수강료는 결제선생
--                   에서 따로 보시고」). 그러니 「안내를 보냈나」 는 기억에만
--                   남아 있었다. 이것 하나가 진짜로 비어 있던 자리다.
--
-- ── 언제 뜨나 ─────────────────────────────────────────────
--
-- 매달 25일 마감, 3일 전(22일)부터 할일 목록에 뜬다. 회차 확정이 25일부터
-- 시작하니(0123) 확정하고 나서 안내가 나가는 순서와 맞는다
-- (app/parent/MonthConfirm — 「회차를 확정하고 수강료 안내가 나간다」).
-- 날짜가 안 맞으면 원장님이 화면에서 바로 고치시면 된다.
--
-- ── 두 번 생기지 않는다 ────────────────────────────────────
--
-- 이 INSERT 는 같은 제목이 이미 있으면 넘어간다 (아래 not exists).
-- 그리고 여기서 생기는 **할일**은 tasks.auto_key = 'routine:<id>:<날짜>' 를
-- 달고 나오는데 그 칸은 통째로 유일하다 (0028·0061). 그래서
--   · 같은 달에 두 번 뜨는 일이 없고,
--   · 「했음」 으로 체크해 넘긴 것이 다시 살아나지도 않으며,
--     (syncRoutines 는 auto_key 가 이미 있으면 손대지 않는다)
--   · 다음 달이 오면 날짜가 달라지므로 **새 줄로 다시 뜬다.**
-- 「이번 달 했나」 를 규칙 쪽에 따로 적어두지 않는다 — 두 군데가 되면 어긋난다.

insert into public.todo_routines
  (title, repeat_kind, day_of_month, lead_days, priority, note, active, sort)
select
  '수강료 안내 보내기',
  'monthly',
  25,
  3,
  1,
  '다음 달 회차를 먼저 확정하고 보냅니다 (일정 → 회차 관리). 회차 미확정은 대시보드 「남은 일」 이 25일부터 알려줍니다.',
  true,
  10
where not exists (
  select 1 from public.todo_routines where title = '수강료 안내 보내기'
);

-- 밖에서 「이 SQL 을 돌렸나」 를 물어볼 자국. 표·칸이 안 바뀌는 데이터
-- 전용 마이그레이션이라(0174 와 같은 처지) 표식 함수로만 확인할 수 있다.
create or replace function public.fixed_routines_on()
returns boolean language sql stable as $$ select true $$;
grant execute on function public.fixed_routines_on() to authenticated;

