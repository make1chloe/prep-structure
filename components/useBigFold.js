"use client";

import { useState } from "react";

/**
 * **대단원은 어느 화면에서 열든 접힌 채로 시작한다**
 * (원장님 2026-08-28 — 「진도 정할 때 **어느 페이지에서 열든**, 대단원은
 *  **무조건** 접힌 상태로 두고, **제목 클릭 시** 열리게 해줘」).
 *
 * ── 왜 훅 한 벌인가 ──────────────────────────────────
 *
 * 단원 위계를 그리는 자리는 둘이다 — 진도 판(BookProgress)과 단원 골라
 * 찍기 팝오버(ProgressPickModal). 접는 규칙을 화면마다 따로 적으면
 * 두 벌이 되고, 언젠가 한쪽만 「진행 중인 대단원은 펴두자」 같은 예외가
 * 붙는다. 그러면 「어느 페이지에서 열든 같다」 는 약속이 깨진다.
 * 묶는 판단이 components/unitGroups 한 벌인 것과 같은 이유다.
 *
 * ── 규칙 ────────────────────────────────────────────
 *
 *   ① 기본은 **무조건 접힘.** 진행 중이든 방금 찍었든 예외 없다
 *      (원장님이 「무조건」이라고 하셨다 — 예외가 하나 생기면 「왜 이건
 *       열려 있지」 를 매번 다시 생각하시게 된다).
 *   ② **대단원이 없는 단원은 늘 보인다.** 접을 머리가 없는데 감추면
 *      판이 통째로 빈 것처럼 보인다.
 *   ③ **글자로 거르는 중에는 전부 펴진다.** 「단원 찾기」로 친 글자에
 *      걸린 것이 접혀 있으면 찾은 보람이 없다. 글자를 지우면 도로 접힌다
 *      (편 것을 기억해 두었다가 되돌린다 — 손으로 편 것은 안 잃는다).
 */
export function useBigFold(query = "") {
  const [open, setOpen] = useState(() => new Set());
  const searching = !!(query || "").trim();

  return {
    searching,
    /** 이 대단원의 묶음을 지금 그릴까 */
    isOpen: (big) => !big || searching || open.has(big),
    toggle: (big) =>
      setOpen((s) => {
        const n = new Set(s);
        n.has(big) ? n.delete(big) : n.add(big);
        return n;
      }),
  };
}
