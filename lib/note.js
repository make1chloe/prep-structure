/**
 * **화면에 적을 만한 말만 남긴다.**
 *
 * 원장님 (2026-08-07)
 *   「모든 페이지에 학생 학부모 포함 노션이관 언급하지마 정보과잉이야」
 *
 * ── 왜 「노션 이관」 이 붙어 있었나 ─────────────────────────
 *
 * 옛 자료를 옮겨오면서 **어디서 온 줄인지** 를 적어두었다. 옮기던 그 주에는
 * 쓸모가 있었다 — 이상한 줄이 있으면 손으로 넣은 것인지 옮겨온 것인지
 * 가려야 했으니까.
 *
 * 그런데 그 일은 끝났고, 지금 이 말은 **읽는 사람에게 아무것도 아니다.**
 * 어머니께는 더욱 그렇다 — 「노션」 이 뭔지 모르시고, 알 필요도 없다.
 * 한 줄에 붙는 말이 하나 늘면 정작 봐야 할 「7/3 결석」 이 그만큼 뒤로 밀린다.
 *
 * **지우지는 않는다.** DB 에는 그대로 두고 화면에서만 뗀다 — 나중에
 * 「이 줄이 어디서 왔지」 를 물어야 할 일이 생길 수 있고, 그때 지워버린
 * 것은 되돌릴 수가 없다.
 *
 * 괄호 안의 말은 살린다. 「노션 이관 (결석일이 생성일 기준이라 다를 수
 * 있음)」 에서 정작 알아야 할 것은 괄호 쪽이다.
 */

const FROM = /노션\s*이관/g;

export function cleanNote(note) {
  let s = (note || "").toString().trim();
  if (!s) return "";
  if (!FROM.test(s)) return s;
  FROM.lastIndex = 0;

  s = s.replace(FROM, "").trim();
  // 남은 것이 괄호로만 싸여 있으면 껍데기를 벗긴다
  const m = s.match(/^[(（]\s*(.*?)\s*[)）]$/);
  if (m) s = m[1].trim();
  return s;
}

/**
 * **「[전국]」 을 떼고 보여준다** (원장님, 2026-08-07 —
 * 「전국은 왜 표시하는거야? 그냥 그것도 표시하지마. 안 표시하면 전국이겠지,
 * 표시를 해야 그 학교 특정일거고. 정보를 과도하게 늘리지말자」).
 *
 * 나이스에서 받은 줄은 학교 이름이 앞에 붙는다 (「해송고 기말고사」).
 * 수능·모의고사처럼 학교와 상관없는 것은 붙일 이름이 없어서 「[전국]」 을
 * 달아두었는데, **이름이 없는 것이 이미 전국이라는 뜻**이다.
 *
 * 새로 받는 줄에는 아예 안 붙인다 (lib/neis.js). 이미 들어와 있는 줄은
 * 제목이 그대로라, 화면에서 뗀다.
 */
export function cleanTitle(title) {
  return (title || "").toString().replace(/^\[전국\]\s*/, "").trim();
}
