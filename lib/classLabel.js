/**
 * **반 이름을 화면에 어떻게 적나 — 한 곳** (원장님, 2026-08-11 —
 * 「19:30-22:00 화목 7:30~10:00 이게 왜 중복으로 보이는지 모르겠어 헷갈려.
 * 그리고 시간표시가 더 헷갈리게 해」).
 *
 * 노션에서 옮겨온 반 이름에는 시간이 **이름 안에** 적혀 있다 —
 * 「화목 7:30~10:00」. 그런데 반에는 시작·끝 시간 칸이 따로 있고, 화면은
 * 그 칸을 이름 앞에 붙인다. 그래서 시간이 **두 번**, 그것도 12시간(7:30)과
 * 24시간(19:30) 표기로 **다르게** 나왔다.
 *
 * 칸이 진짜다 (수업 시간 계산이 전부 칸을 본다). 그래서 화면에서는
 * **이름 속의 시간을 지우고, 시간은 칸에서 한 번만** 적는다.
 * 이름을 DB 에서 고치지는 않는다 — 원장님이 반 관리에서 고치실 수 있게
 * 거기서는 적힌 그대로 보인다.
 */

/** 이름에서 시간 표기를 걷어낸다 — 「화목 7:30~10:00」 → 「화목」 */
export function cleanClassName(name = "") {
  const t = String(name)
    // 범위: 7:30~10:00 · 19:30-22:00 · 7시30분~10시
    .replace(
      /\d{1,2}\s*[:시]\s*\d{0,2}\s*분?\s*[~∼\-–]\s*\d{1,2}\s*[:시]?\s*\d{0,2}\s*분?/g,
      " "
    )
    // 남은 낱개 시각: 7:30
    .replace(/\d{1,2}\s*:\s*\d{2}/g, " ")
    .replace(/\s+/g, " ")
    .replace(/^[\s·,\-–~]+|[\s·,\-–~]+$/g, "")
    .trim();
  // 이름이 시간뿐이었으면 지우지 않는다 — 빈 이름보다는 겹치는 이름이 낫다
  return t || String(name).trim();
}

/** 시작-끝 시간을 칸에서 — 「19:30-22:00」 */
function classTime(klass = {}) {
  const cut = (t) => (t ? String(t).slice(0, 5) : "");
  const s = cut(klass.start_time);
  const e = cut(klass.end_time);
  if (!s) return "";
  return e ? `${s}-${e}` : s;
}

/** 화면에 적는 한 줄 — 「19:30-22:00 화목」 */
export function classLabel(klass = {}) {
  return [classTime(klass), cleanClassName(klass.name)].filter(Boolean).join(" ");
}
