/**
 * **교재에 붙이는 인쇄물 — 무엇을 어떤 차례로 실을까** (원장님 2026-08-31
 * 「학습항목 적어놓은 걸, 교재에 붙일 인쇄 자료로 만들려고 해」).
 *
 * 종이 한 장이 「이 책은 이렇게 공부한다」가 되어 교재 앞에 붙는다.
 * 그리는 것은 app/textbooks/print 가 하고, **무엇을 어떤 차례로 실을지는
 * 여기 한 곳**에서 정한다 (CLAUDE.md — 판단은 lib 에).
 *
 * ── 뽑는 규칙을 새로 만들지 않았다 (원칙 1) ─────────────────
 *
 * 이 파일에는 「어느 교재의 루틴인가」 를 고르는 셈이 **없다.** 그것은
 * 이미 app/textbooks/routineActions.listRoutine 한 곳에 있고 (교재 루틴이
 * 한 줄이라도 있으면 그것, 없으면 그 교재 영역의 루틴 — 0137), 인쇄도
 * 교재 화면과 **똑같이 그 함수를 부른다.** 여기서 다시 풀면 화면과 종이가
 * 서로 다른 루틴을 말하는 날이 온다.
 *
 * 갈래 셋(등원 학습·집 숙제·예습)의 이름과 차례도 새로 안 적었다 —
 * lib/routineAdd.ADD_BUCKETS 그대로다. 그 목록이 이미 `step` 칸으로
 * routine_steps 의 inclass_items · home_items · home_next 와 짝지어져
 * 있어서, 갈래가 하나 늘면 인쇄물도 저절로 따라 늘어난다.
 *
 * ── 왜 갈래를 종이에도 드러내나 ──────────────────────────
 *
 * 셋은 **뜻이 다르다.** 등원 학습은 학원에서 선생님과, 집 숙제는 오늘 한
 * 단원으로, 예습은 다음 단원으로 한다 (0136). 종이에서 이것이 뭉쳐 있으면
 * 아이는 집에서 등원 학습까지 하려 들거나, 예습을 오늘 단원으로 한다.
 * 그래서 갈래마다 머리를 달고, 차례는 **하루가 흘러가는 차례**
 * — 학원(등원) → 그날 밤 숙제 → 다음 시간 몫(예습) — 으로 둔다.
 * 이 차례는 ADD_BUCKETS 의 차례이자 교재 화면(RoutineEditor)이 이미
 * 그리는 차례이기도 하다. 세 곳이 같은 차례라야 손이 안 헷갈린다.
 *
 * ── 회차와 회독 ────────────────────────────────────────
 *
 * 한 줄(step)이 **한 수업 회차**다 (0035). 회차는 **다 싣는다** — 한 장에
 * 1회차·2회차·3회차가 차례로 서야 「이 책은 이렇게 공부한다」 가 된다.
 * 골라 싣게 하면 종이가 회차 수만큼 늘고, 아이가 오늘 몇 회차인지 알아야
 * 어느 종이를 볼지 정할 수 있다.
 *
 * **회독(round, 0135)도 안 거른다.** 거를 수가 없다 — 회독은 학생마다
 * 다른데(student_textbooks.round) 이 종이는 학생이 아니라 **책에** 붙는다.
 * 대신 그 줄이 몇 회독부터인지 머리에 적어, 1회독 아이가 3회독 줄을
 * 건너뛸 수 있게 한다.
 */

import { ADD_BUCKETS } from "@/lib/routineAdd";

/**
 * 체크리스트를 줄로 나누는 규칙은 여기 없다 —
 * lib/homeworkView.checklistLines 한 벌을 화면도 종이도 그대로 쓴다.
 * 두 벌로 풀면 화면엔 세 줄인데 종이엔 네 줄이 되는 날이 온다.
 */

/**
 * 인쇄할 판을 짠다.
 *
 * @param steps   listRoutine 이 준 줄들 (이미 sort 차례)
 * @param itemOf  학습 항목 id → 항목 (loadHomeworkItems 의 Map.get 을 그대로)
 * @returns 회차 블록 목록. 항목이 하나도 안 붙은 회차는 뺀다 — 빈 회차를
 *          종이에 세우면 아이는 「여긴 뭐 하는 데지」 를 매번 다시 읽는다.
 */
export function printPlan(steps, itemOf) {
  let no = 0;                       // 번호는 **종이 전체를 관통한다** (아래 주석)
  const out = [];
  (steps || []).forEach((s, i) => {
    const groups = [];
    for (const b of ADD_BUCKETS) {
      const rows = (s?.[b.step] || [])
        .map((id) => itemOf(id))
        .filter(Boolean)
        .map((it) => ({
          no: ++no,
          item: it,
          /**
           * 루틴에만 붙는 주의 (0139 — 「클카 스크램블[6000점 이상]」).
           * 학습 방법은 어디서나 같은 「하는 법」이고, 이것은 **이 책
           * 이 회차에서만** 다른 조건이다. 빼면 종이가 시키는 것과
           * 실제로 나가는 숙제가 어긋난다.
           */
          note: (s?.item_notes && s.item_notes[it.id]) || "",
        }));
      if (rows.length) groups.push({ key: b.key, label: b.label, hint: b.hint, rows });
    }
    if (groups.length) {
      out.push({
        key: s?.id || `i${i}`,
        no: out.length + 1,          // 실린 회차만 1,2,3… (빈 회차를 건너뛰어도 번호가 안 빈다)
        label: (s?.label || "").trim(),
        round: s?.round || null,
        groups,
      });
    }
  });
  return out;
}

/**
 * 번호를 **종이 전체에 하나로** 매기는 까닭 —
 * 회차마다 1부터 다시 세면 종이에 「1번」 이 세 개가 된다. 아이가 「3번
 * 했어요」 라고 할 때 어느 3번인지 되물어야 하고, 동그라미 칸을 세어
 * 「오늘 몇 개 했나」 를 보는 일도 안 된다. 한 줄로 흐르는 번호라야
 * 종이 한 장이 하나의 차례가 된다.
 *
 * 같은 항목이 여러 회차에(또는 한 회차의 등원과 숙제 양쪽에) 들어 있어도
 * **묶지 않는다.** 그건 두 번 하는 것이지 한 번 하는 것이 아니다
 * (lib/routineAdd — 「등원과 숙제 양쪽에 같은 항목을 넣는 것도 그대로
 * 된다. 루틴이 원래 그것을 허용한다」).
 */

/** 종이에 실리는 칸 수 — 「인쇄용으로 보기」 를 내어줄지 정할 때 쓴다 */
export function printCount(plan) {
  return (plan || []).reduce(
    (n, st) => n + st.groups.reduce((m, g) => m + g.rows.length, 0),
    0
  );
}
