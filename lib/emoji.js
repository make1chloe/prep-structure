/** 그림이 겹치나 — 검사와 화면이 같은 셈을 쓴다(원칙-1) */
export const dupes = (table) => {
  const by = new Map();
  for (const [k, e] of Object.entries(table)) { if (!by.has(e)) by.set(e, []); by.get(e).push(k); }
  return [...by].filter(([, ks]) => ks.length > 1).map(([e, ks]) => `${e} ← ${ks.join(" · ")}`);
};
