/**
 * 고를 수 있는 시간표 — **중복 가능**.
 *
 * `key` 는 DB 에 남는 글자다. **바꾸면 이미 접수된 것이 안 읽히므로**
 * 시간이 바뀌어도 key 는 그대로 두고 label 만 고친다.
 */
export const SLOTS = [
  { key: "elem-mw",   group: "초등",     days: "월·수", time: "2:50~4:50" },
  { key: "elem-tt",   group: "초등",     days: "화·목", time: "2:50~4:50" },
  { key: "mid-mw",    group: "중1~중3",  days: "월·수", time: "5:00~7:30" },
  { key: "mid-tt",    group: "중1~중3",  days: "화·목", time: "5:00~7:30" },
  { key: "high-mw",   group: "중2~고3",  days: "월·수", time: "7:30~10:00" },
  { key: "high-tt",   group: "중2~고3",  days: "화·목", time: "7:30~10:00" },
];

export const slotLabel = (s) => `${s.group} ${s.days} ${s.time}`;

/** DB 에 남은 key 들 → 사람이 읽는 글자 (모르는 key 는 그대로 둔다) */
export function slotText(keys = []) {
  return (keys || [])
    .map((k) => {
      const s = SLOTS.find((x) => x.key === k);
      return s ? slotLabel(s) : k;
    })
    .join(" · ");
}

