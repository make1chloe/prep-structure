/**
 * 고른 것과 적어주신 것을 **한 줄로** 합친다 — 「재원생 소개 (김하늘)」.
 *
 * 칸을 따로 두면 SQL 을 하나 더 돌려야 하고, 상담 목록·검색·엑셀 내려받기가
 * 전부 그 칸을 알아야 한다. 어차피 사람이 읽는 글자라 합쳐서 남긴다.
 */
export function sourceText(source, why) {
  const s = (source || "").trim();
  const w = (why || "").trim();
  if (!s) return null;
  return w ? `${s} (${w})` : s;
}

