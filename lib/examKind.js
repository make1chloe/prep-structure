/**
 * **시험 이름 분류 — 온 앱에서 이 한 곳만 쓴다** (원장님, 2026-08-09 —
 * 「학사일정이 여전히 제대로 로딩되지 않고 있어. 단편적으로 반영하다 보니
 * 예외 규칙이 너무 많아진 것 같아. 먼저 한국 초중고가 시험을 어떻게 보는지
 * 조사해서 파악하고, 일정 관련 코드를 전면 재검토해서 바로잡아」).
 *
 * ── 무엇이 문제였나 ──────────────────────────────────────
 *
 * 같은 판단이 **두 벌**이었다. lib/neis.js 는 제 정규식(EXAM · NOT_EXAM ·
 * NATIONWIDE)으로, lib/examList.js 는 또 제 정규식(isMockExam · isSuneung)으로
 * 같은 이름을 갈랐다. 전수 대조를 돌려보니 —
 *
 *   「6월 모의평가」   neis: 전국      examList: **내신**   ← 서로 반대
 *   「6월 모평」       neis: **행사**  examList: 모의고사   ← 회차가 안 생김
 *   「수행평가」       neis: 행사      examList: **내신**   ← 옛 줄에 범위 재촉
 *
 * 두 벌이 어긋난 채로 고치기를 거듭하니, 고칠 때마다 한쪽에만 예외가 붙어서
 * 누더기가 됐다. 그래서 갈래 규칙을 여기 **한 곳**에 두고, 두 파일 모두
 * 여기서 가져다 쓴다.
 *
 * ── 한국 초·중·고 시험 제도 (2026-08-09 조사) ─────────────
 *
 * 자세한 조사는 docs/시험-일정-조사.md 에 있다. 갈래에 필요한 뼈대만 —
 *
 * **1. 내신 지필고사 (school)** — 학교가 내고, 학교마다 날짜가 다르다.
 *    학기마다 중간·기말 두 번, 며칠에 걸쳐 여러 과목을 본다. **하루짜리가
 *    아니다.** 이것만이 시험범위가 있고, 학원이 대비 자료를 만드는 시험이다.
 *    이름 표기가 학교마다 다르다: 1회고사 · 1차고사 · 제2차 지필평가 · 2차시험.
 *    예외 — 중1은 자유학기제라 지필고사가 대부분 없다. 중3 2학기 기말은 고입
 *    때문에 11월로 당겨지거나 생략되고, 고3 2학기는 수시 일정 때문에 중간만
 *    9월에 보는 학교가 많다. 이런 「안 보는 회차」 는 이름으로 가를 수 없어서
 *    exam_skips(「안 봄」 처리)로 다룬다.
 *
 * **2. 모의고사 (mock)** — 교육청 「전국연합학력평가」 + 평가원 「모의평가」.
 *    전국이 같은 날, 학년마다 다른 시험지로 하루에 본다. 고1·2는 한 해 4회
 *    (3·6·9·10월), 고3은 학평 4회(3·5·7·10월)에 모평 2회(6·9월)를 더해 6회.
 *    범위가 없으니 대비 자료도 없고, 성적만 회차에 붙는다. 중학생은 안 본다.
 *    학교가 「전국연합학력평가」 「6월 모의평가」 「모평」 「학력평가」 등으로
 *    제각각 적는데 **전부 같은 갈래**다.
 *
 * **3. 대수능 (suneung)** — 11월 하루. 고3·N수생만 본다. 고1·2는 학교가
 *    시험장이 되고 선생님들이 감독을 가서 그날 쉰다 (「대수능시험 휴업일」).
 *    대비도 성적 입력도 이 앱에서 할 일이 없다 — 달력에 하루 적히면 끝이다.
 *    주의: 대「학수학능력」시험에는 「수능」 두 글자가 붙어 있지 않다.
 *    「수능 모의평가」 처럼 모의가 붙으면 mock 이다.
 *
 * **4. 지필이 아닌 평가 (assess)** — 수행평가 · 학업성취도평가 · 진단평가 ·
 *    기초학력평가. 이름에 「평가」 가 들어 있지만 시험 기간이 아니다.
 *    회차를 만들면 안 되고, 만들어져 있던 옛 줄에 범위를 재촉해서도 안 된다.
 *
 * **5. "" (시험이 아님)** — 체육대회 · 방학 · 졸업식 같은 나머지 전부.
 */
export function classifyExam(name) {
  const t = (name || "").toString();
  if (!t.trim()) return "";

  // 지필이 아닌 평가 — 「평가」 라는 말에 속지 않는 것이 먼저다
  if (/(수행|학업성취|성취도|진단|기초학력|졸업|자격|경시|인증|검정)/.test(t)) return "assess";

  // 대수능 — 「모의」 가 붙으면 평가원 모의고사다
  if (/(대학\s*수학\s*능력|대?수능)/.test(t) && !/(모의|모평|연합|학력\s*평가)/.test(t)) {
    return "suneung";
  }

  // 모의고사 — 교육청 학평과 평가원 모평을 다 받는다
  if (/(전국\s*연합|학력\s*평가|모의\s*평가|모의\s*고사|모평)/.test(t)) return "mock";

  // 내신 지필 — 학교마다 다른 표기(1회고사 · 지필평가 · 2차시험)를 넓게 받는다
  if (/(고사|시험|평가|지필)/.test(t)) return "school";

  /**
   * **「2학기 중간」 처럼 뒷말을 떼고 적는 학교가 있다** (2026-08-09).
   *
   * 위 낱말들(고사·시험·평가·지필)이 하나도 없어서 시험이 아닌 것으로
   * 흘러갔다. 그러면 그 학교는 **회차가 통째로 안 생긴다** — 목록에서
   * 그냥 없는 것처럼 보이고, 왜 없는지도 알 수 없다.
   *
   * 다만 「중간」 「기말」 두 글자는 다른 데도 쓰인다 (중간놀이 · 기말 방학).
   * 그래서 **그 말로 끝날 때만** 시험으로 본다 — 「2학기 중간」 은 받고
   * 「중간놀이시간」 은 안 받는다.
   */
  if (/(중간|기말)\s*$/.test(t.trim())) return "school";

  return "";
}
