/**
 * **단원 이름 짓는 법 한 벌** (원장님 2026-08-23 — 「단원 만들기도 1과가
 * 과 1로 보임」).
 *
 * 영어는 앞에 붙고(`Unit 1`), 한국어는 **뒤에 붙는다**(`1과`, `3강`).
 * 「과 1」 은 우리말로 읽히지 않는다. 만드는 곳(서버)과 미리보기(화면)가
 * 각자 문자열을 이어 붙이면 반드시 한쪽만 고쳐지므로 여기 한 곳에 둔다.
 */
export function unitName(prefix, n) {
  const p = (prefix || "").trim();
  if (!p) return String(n);
  // 한글만으로 된 말은 뒤에 붙인다 (과 · 강 · 단원 · 회 · 장 · 차시)
  if (/^[가-힣]+$/.test(p)) return `${n}${p}`;
  return `${p} ${n}`;
}
