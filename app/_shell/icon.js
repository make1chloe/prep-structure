/** 아이콘만 있는 손의 **이름과 툴팁은 한 벌**((어51) · 2026-09-16).
 *  원장님 9/16: 「아이콘 자체가 너무 시각적으로 빈약해. 아이콘으로만 정보를 표시한경우에는 툴팁이라고하나,
 *  그런걸로 마우스를 대고 있으면 '다음시간으로 미루기', 같이 설명을 띄워」.
 *  원장님 9/15: 「tooltips 명사 1개 두 개로 끝내라」 → 이름(aria-label)은 짧은 이름 · 툴팁(title)은 뜻이 통하는 설명.
 *  둘을 따로 적으면 반드시 어긋나므로(원칙-1) 한 벌로 만들어 퍼뜨린다: `<button {...icon("다음 시간", "다음 시간으로 미루기")}>⏭</button>`.
 *  글이 함께 보이는 손에는 쓰지 않는다(글이 이미 이름이라 툴팁은 군더더기다 · (어39) 대전제-21). */
export const icon = (name, tip) => ({ "aria-label": name, title: tip ?? name });
