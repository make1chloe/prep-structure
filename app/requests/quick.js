/**
 * **빨리 누를 수 있는 답장 문구.**
 *
 * 원장님 (2026-08-07) — 「학생에게는 확인완료, 조정필요, 학부모님께는
 * 확인하였습니다 뭐 그런 문구를 넣어줘. OX 상황에 맞게」
 *
 * 답장을 매번 손으로 적으면 결국 안 적게 된다. 그러면 어머니 화면에는
 * 「제출 완료」 만 남고, 우리가 봤는지 아닌지는 여전히 안 보인다.
 *
 * 말투를 **받는 사람에 따라 나눈다.** 아이에게 「확인하였습니다」 는 어색하고,
 * 어머니께 「확인완료」 는 무뚝뚝하다. 같은 뜻이라도 닿는 느낌이 다르다.
 *
 * ── 왜 actions.js 가 아니라 여기인가 ─────────────────────
 *
 * actions.js 는 "use server" 파일이라 **async 함수만 export** 할 수 있다.
 * 상수를 거기서 내보내면 화면을 열 때 터진다 — 빌드는 통과해서 더 늦게
 * 발견된다 (app/consult/status.js 에 같은 이야기가 적혀 있다).
 */
export const QUICK = {
  student: { ok: "확인완료", no: "조정필요" },
  parent: {
    ok: "확인하였습니다.",
    no: "확인하였습니다. 일정 조정이 필요해 연락드리겠습니다.",
  },
};

/** 이 요청을 보낸 사람에게 맞는 문구 */
export function quickFor(role, ok) {
  const set = role === "parent" ? QUICK.parent : QUICK.student;
  return ok ? set.ok : set.no;
}
