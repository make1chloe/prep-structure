// 세 번이면 **안 한 적도 없는 아이가 반성문 대상**이 된다.
// 오류는 안 난다 — 그래서 규칙을 여기 한 곳에 두고 검사로 못 박는다.
export const CATEGORIES = [
  "단어", "독해", "문법", "영작", "듣기", "노트", "내신", "특강",
  "공지", "다음테스트",
  "기타",
];

/**
 * **검사 대상이 아닌 것** — 한 곳에서만 정한다.
 *
 * 화면마다 따로 적으면 한 곳을 빠뜨리고, 빠뜨린 그 화면에서 경고가 쌓인다.
 * 단원평가(unit_test)도 같은 성격이라 여기서 같이 본다.
 */
export const NO_CHECK_CATEGORIES = ["공지", "다음테스트"];

export function isNoCheck(item) {
  if (!item) return false;
  return !!item.unit_test || NO_CHECK_CATEGORIES.includes(item.category || "");
}

