// 학생 첫 화면 — ⚠️ 옛 SW 가 알림을 눌렀을 때 여는 기본 주소다. 비어 있어도 **404 는 안 된다**
// ⚠️ 로그아웃 단추를 빼지 마라 (대전제 10). 문지기가 학생을 `/login` 에서 여기로 되돌리므로,
//    이 화면에 없으면 홈 화면에 깐 앱에서 **계정을 바꿀 길이 아예 없다** — 실측으로 그랬다.
//    단추 모양·동작은 `app/logout-button.js` 한 벌뿐이다 (원칙 1).
//
// ⚠️⚠️ **문지기는 역할로 이 화면을 안 지킨다.** `middleware.js` 는 「첫 화면 고르기」만 하고,
//    `/me` 는 로그인만 했으면 누구나 200 이다(실측 — 학부모 세션으로 열림).
//    그래서 **역할 가르기를 `./read.js` 안에서 스스로 한다.** 그것을 지우면 그날부터
//    학부모 폰에 학생 화면이 그대로 열린다 — 진도 레이스처럼 **학부모에게 보내면 안 되는 것**이
//    이 화면에 사는데(계획 「학부모 화면에서 지킬 것」), 자료는 접근 규칙이 막아도 화면은 열린다.
//
// ⚠️ 이 화면은 **읽기만** 하는 서버 컴포넌트다. 그리기는 `./screen.js`(클라이언트)가 하고,
//    셈은 `./derive.js` 와 `lib/` 이 한다. 여기에는 판단이 한 줄도 없다.
import LogoutButton from "../logout-button";
import Screen from "./screen";
import { 학생화면읽기, 글, 조회_상한 } from "./read";

// ⚠️ 쿠키를 읽는 화면이다 — **미리 만들어 두면 안 된다.** 미리 만들면 남의 아이 화면이 굳는다
export const dynamic = "force-dynamic";

export default async function Me() {
  const d = await 학생화면읽기();

  // ── 아무것도 못 읽는 자리 — ⚠️ **빈 화면을 예쁘게 만들지 않고 까닭을 적는다**(대전제 0)
  if (d.열쇠없음 || d.막힘) {
    return (
      <main className="wrap">
        <h1>클로이영어</h1>
        <p className="sunk">{d.막힘 ?? "앱 설정이 아직 덜 됐습니다. 원장님께 알려주세요."}</p>
        {d.열쇠없음 && <p><small>{d.열쇠없음}</small></p>}
        {d.왜들?.length > 0 && <ul>{d.왜들.map((w, i) => <li key={i}><small>{w}</small></li>)}</ul>}
        <LogoutButton />
      </main>
    );
  }

  // ⚠️ 조회가 상한을 넘으면 **조용히 넘기지 않는다.** 아이 폰이 느려지는 것을 아무도 모르게 된다
  const 왜들 = d.조회수 > 조회_상한
    ? [...d.왜들, `⚠️ 이 화면이 서버에 ${d.조회수}번 물었습니다 (상한 ${조회_상한}). 원장님께 알려주세요.`]
    : d.왜들;

  return (
    <Screen
      오늘={d.오늘}
      학생={d.학생}
      카드순서={d.카드순서}
      역할={d.역할}
      권한={d.권한}
      권한왜={d.권한왜}
      오늘판={d.오늘판}
      오늘줄={d.오늘줄}
      빈카드숨김={d.빈카드숨김}
      교재들={d.교재들}
      진도줄={d.진도줄}
      이의들={d.이의들}
      진도체크열림={d.진도체크열림}
      달력={d.달력}
      글={글}
      왜들={왜들}
    />
  );
}
